<?php

declare(strict_types=1);

namespace GitDeploy;

/**
 * Turns a Forge-style deploy script into a runnable bash script by replacing the
 * macros with calls to the plugin's helper.
 */
final class ScriptBuilder
{
    public const CREATE = '$CREATE_RELEASE()';
    public const ACTIVATE = '$ACTIVATE_RELEASE()';
    public const RESTART_QUEUES = '$RESTART_QUEUES()';
    public const REQUIRE_NODE = '$REQUIRE_NODE()';
    public const MAX_LENGTH = 65536;

    /**
     * sha1 of earlier default scripts (normalized). A site whose script still equals one of
     * them is offered the current default, which has the Node.js check.
     */
    private const PREVIOUS_DEFAULTS = [
        'e40986f883b6313e84f0391551fc9b41c721c6c4', // 0.1.x: skipped the frontend build when npm was missing
    ];

    private const MACROS = [
        self::CREATE => '__laravel_github_deploy create-release',
        self::ACTIVATE => '__laravel_github_deploy activate-release',
        self::RESTART_QUEUES => '__laravel_github_deploy restart-queues',
        self::REQUIRE_NODE => '__laravel_github_deploy require-node',
    ];

    public static function normalize(string $script): string
    {
        $script = str_replace(["\r\n", "\r"], "\n", $script);
        return rtrim($script) . "\n";
    }

    /** @return list<string> */
    public static function validate(string $script): array
    {
        $errors = [];
        if (strlen($script) > self::MAX_LENGTH) {
            $errors[] = 'The deploy script is too long (max 64 KB).';
        }
        $create = substr_count($script, self::CREATE);
        $activate = substr_count($script, self::ACTIVATE);
        if ($create !== 1) {
            $errors[] = 'The deploy script must contain ' . self::CREATE . ' exactly once.';
        }
        if ($activate !== 1) {
            $errors[] = 'The deploy script must contain ' . self::ACTIVATE . ' exactly once.';
        }
        if ($create === 1 && $activate === 1 && strpos($script, self::CREATE) > strpos($script, self::ACTIVATE)) {
            $errors[] = self::CREATE . ' must come before ' . self::ACTIVATE . '.';
        }
        if (str_contains($script, "\0")) {
            $errors[] = 'The deploy script contains invalid characters.';
        }
        return $errors;
    }

    public static function build(string $script): string
    {
        $header = <<<'BASH'
#!/bin/bash
# Generated by Laravel Github deploy. Edit the deploy script in DirectAdmin instead.
set -eo pipefail
__laravel_github_deploy() { "$GIT_DEPLOY_PHP_CLI" -c "$GIT_DEPLOY_PHP_INI" "$GIT_DEPLOY_HELPER" "$@"; }


BASH;
        return $header . strtr(self::normalize($script), self::MACROS);
    }

    public static function defaultScript(Env $env): string
    {
        $tpl = @file_get_contents($env->pluginDir . '/templates/deploy/laravel.sh');
        return is_string($tpl) ? self::normalize($tpl) : self::CREATE . "\n\ncd \$DEPLOY_RELEASE_DIRECTORY\n\n" . self::ACTIVATE . "\n";
    }

    /** Whether $script is an earlier default script, unchanged by the user. */
    public static function isPreviousDefault(string $script): bool
    {
        return in_array(sha1(self::normalize($script)), self::PREVIOUS_DEFAULTS, true);
    }
}
